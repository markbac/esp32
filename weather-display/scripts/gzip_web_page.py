"""PlatformIO pre-build script: gzip the web dashboard into a generated header.

include/web_page.h stays the human-editable source (a raw string literal).
This script extracts the HTML, gzips it (deterministically, mtime 0) and
writes $BUILD_DIR/generated/web_page_gz.h with WEB_PAGE_GZ / WEB_PAGE_GZ_LEN.
The web server sends it with "Content-Encoding: gzip", which every browser
unpacks, so the dashboard takes ~16 KB of flash instead of ~48 KB.

The header is only rewritten when the HTML changes, so it does not force a
rebuild every time.
"""
import gzip
import io
import os

Import("env")  # noqa: F821 - provided by PlatformIO/SCons

SRC = os.path.join(env.subst("$PROJECT_DIR"), "include", "web_page.h")  # noqa: F821
OUT_DIR = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
OUT = os.path.join(OUT_DIR, "web_page_gz.h")


def build():
    text = open(SRC, encoding="utf-8").read()
    start = text.index('R"HTML(') + len('R"HTML(')
    end = text.index(')HTML"', start)
    html = text[start:end].encode("utf-8")

    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as gz:
        gz.write(html)
    data = buf.getvalue()

    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    header = (
        "// Generated by scripts/gzip_web_page.py from include/web_page.h - do not edit.\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
        f"// {len(html)} bytes of HTML, {len(data)} bytes gzipped.\n"
        "static const uint8_t WEB_PAGE_GZ[] = {\n  " + ",\n  ".join(lines) + "\n};\n"
        "static const size_t WEB_PAGE_GZ_LEN = sizeof(WEB_PAGE_GZ);\n"
    )
    os.makedirs(OUT_DIR, exist_ok=True)
    if not os.path.exists(OUT) or open(OUT, encoding="utf-8").read() != header:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(header)
    print(f"web page: {len(html)} -> {len(data)} bytes gzipped")


build()
env.Append(CPPPATH=[OUT_DIR])  # noqa: F821
